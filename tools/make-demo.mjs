// Generates public/js/demo.js from the catalog fixture: real coffees with made-up scores.
// Run: node tools/make-demo.mjs
import fs from 'node:fs';
import { parseProduct } from '../public/js/parse.js';
import { familiesOf, estimateAttributes } from '../public/js/flavor.js';

const cat = JSON.parse(fs.readFileSync(new URL('../tests/fixtures/catalog.json', import.meta.url)));
const pick = ['el-salvador-las-brisas', 'colombia-el-para', 'kenia-ibonia-estate', 'ethiopie-banko-gotiti', 'brasil-santa-rosa',
  'guatemala-santa-isabel', 'indonesie-kerinci', 'burundi-rubagabaga', 'costa-rica-sonora', 'peru-cajamarca-la-prosperidad',
  'colombia-finca-el-libano', 'guatemala-familia-mendez', 'mundi', 'colombia-finca-el-paseo'];
const coffees = pick.map((s) => cat.find((p) => p.slug.startsWith(s))).filter(Boolean).map(parseProduct);

let seed = 7;
const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
const half = (v) => Math.max(3, Math.min(9.5, Math.round(v * 2) / 2));

const taste = [
  (c, f, a) => 6.6 + (c.process === 'Natural' ? 1 : 0) + (f.has('berry') ? 0.8 : 0) + (f.has('tropical') ? 0.5 : 0) - (f.has('nutty') ? 1 : 0) - (c.process === 'Washed' ? 0.4 : 0),
  (c, f, a) => 6.4 + (f.has('chocolate') ? 1.1 : 0) + (f.has('caramel') ? 0.8 : 0) + (a.body - 3) * 0.8 - (a.acidity - 3) * 1.1,
  (c, f, a) => 6.8 + (c.process === 'Washed' ? 0.9 : 0) + (f.has('citrus') ? 0.7 : 0) + (f.has('tea') ? 0.6 : 0) - ((c.modifiers || []).includes('Anaerobic') ? 1.2 : 0),
];

const orders = [
  { id: 'demo-o1', date: '2026-09-02', demo: true, note: '' },
  { id: 'demo-o2', date: '2026-10-07', demo: true, note: '' },
  { id: 'demo-o3', date: '2026-11-04', demo: true, note: '' },
];
const out = coffees.map((c, i) => {
  const f = new Set(familiesOf(c));
  const a = estimateAttributes(c);
  const order = orders[Math.min(2, Math.floor(i / 5))];
  const scores = taste.map((fn, pi) => (i === 13 && pi === 2 ? null : half(fn(c, f, a) + (rnd() - 0.5) * 1.2)));
  return { ...c, story: c.story.slice(0, 600), id: `demo-c${i}`, demo: true, orderId: order.id,
    addedAt: `${order.date}T${String(9 + (i % 8)).padStart(2, '0')}:00:00.000Z`, _scores: scores };
});

const src = `// Generated by tools/make-demo.mjs – real Cross Roast coffees with made-up scores.
const ORDERS = ${JSON.stringify(orders)};
const COFFEES = ${JSON.stringify(out)};
export function demoData(people) {
  const coffees = COFFEES.map(({ _scores, ...c }) => {
    const scores = {};
    people.slice(0, 3).forEach((p, i) => { if (_scores[i] != null) scores[p.id] = { score: _scores[i], at: c.addedAt }; });
    return { ...c, scores };
  });
  return { orders: ORDERS.map((o) => ({ ...o })), coffees };
}
`;
fs.writeFileSync(new URL('../public/js/demo.js', import.meta.url), src);
console.log('demo coffees:', out.length, out.map((c) => c.name + ' ' + c._scores.join('/')).join('\n'));
